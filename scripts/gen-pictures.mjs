// Lists every image in public/pictures and writes src/data/pictures.generated.ts.
// Runs automatically before `npm run dev` and `npm run build`, so dropping a photo
// into public/pictures is all it takes to show it in the Pictures app.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "public/pictures";
const out = "src/data/pictures.generated.ts";
const exts = /\.(jpe?g|png|webp|gif|avif)$/i;

let files = [];
try {
  files = readdirSync(dir).filter((f) => exts.test(f) && !f.startsWith("."));
} catch {
  // No folder yet: the app shows an empty folder.
}

const pictures = files
  .map((name) => {
    const { size } = statSync(join(dir, name));
    return { name, src: `/pictures/${encodeURIComponent(name)}`, size };
  })
  .sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));

writeFileSync(
  out,
  `// Generated by scripts/gen-pictures.mjs. Do not edit; add images to public/pictures instead.\n` +
    `export type Picture = { name: string; src: string; size: number };\n\n` +
    `export const pictures: Picture[] = ${JSON.stringify(pictures, null, 2)};\n`
);

console.log(`pictures: ${pictures.length} image(s) from ${dir}`);
